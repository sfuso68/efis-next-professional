#!/usr/bin/env python3
"""Generate EFIS NEXT project status summaries from the master matrix.

The master matrix remains the source of truth. This script parses markdown table
rows carrying stable IDs and produces a compact Markdown and JSON summary.
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ALLOWED = {"DONE", "PARTIAL", "TODO", "BLOCKED", "VERIFY-HW", "LEGACY"}
ID_RE = re.compile(r"^[A-Z][A-Z0-9_-]*-\d{3}$")


def clean(cell: str) -> str:
    return cell.strip().strip("`").strip()


def normalise_status(raw: str) -> str:
    status = clean(raw).upper()
    if status not in ALLOWED:
        allowed = ", ".join(sorted(ALLOWED))
        raise ValueError(
            f"Unsupported project status: {raw!r}; expected exactly one of: {allowed}")
    return status


def parse_matrix(path: Path) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.startswith("|"):
            continue
        cells = [clean(c) for c in line.strip().strip("|").split("|")]
        if not cells or not ID_RE.match(cells[0]):
            continue
        if len(cells) < 5:
            raise ValueError(f"Malformed project row at {path}:{lineno}")
        row = {
            "id": cells[0],
            "requirement": cells[1] if len(cells) > 1 else "",
            "node": cells[2] if len(cells) > 2 else "",
            "status": normalise_status(cells[3]),
            "evidence": cells[4] if len(cells) > 4 else "",
            "raw": line,
        }
        rows.append(row)
    if not rows:
        raise ValueError(f"No requirement rows found in {path}")
    return rows


def area_from_id(item_id: str) -> str:
    return item_id.split("-", 1)[0]


def completion_weight(status: str) -> float:
    return {
        "DONE": 1.0,
        "VERIFY-HW": 0.75,
        "PARTIAL": 0.5,
        "LEGACY": 1.0,
        "TODO": 0.0,
        "BLOCKED": 0.0,
    }[status]


def render(rows: list[dict[str, str]]) -> tuple[str, dict]:
    totals = Counter(r["status"] for r in rows)
    by_area: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        by_area[area_from_id(row["id"])].append(row)

    score = round(100 * sum(completion_weight(r["status"]) for r in rows) / len(rows), 1)
    blocked = [r for r in rows if r["status"] == "BLOCKED"]
    verify_hw = [r for r in rows if r["status"] == "VERIFY-HW"]

    md = [
        "# EFIS NEXT — Project Status (generated)",
        "",
        "> Generated from `docs/status/EFIS_NEXT_MASTER_MATRIX.md`.",
        "> Do not edit this file manually.",
        "",
        f"**Overall weighted progress:** {score}%",
        f"**Requirements tracked:** {len(rows)}",
        "",
        "## Status counts",
        "",
        "| Status | Count |",
        "|---|---:|",
    ]
    for status in ["DONE", "VERIFY-HW", "PARTIAL", "TODO", "BLOCKED", "LEGACY"]:
        md.append(f"| {status} | {totals.get(status, 0)} |")

    md += ["", "## Progress by area", "", "| Area | Progress | Items |", "|---|---:|---:|"]
    area_json = {}
    for area in sorted(by_area):
        items = by_area[area]
        pct = round(100 * sum(completion_weight(r["status"]) for r in items) / len(items), 1)
        md.append(f"| {area} | {pct}% | {len(items)} |")
        area_json[area] = {"progress": pct, "items": len(items)}

    md += ["", "## Hardware verification pending", ""]
    if verify_hw:
        for row in verify_hw:
            md.append(f"- `{row['id']}` — {row['requirement']} ({row['node']})")
    else:
        md.append("- None")

    md += ["", "## Blocked", ""]
    if blocked:
        for row in blocked:
            md.append(f"- `{row['id']}` — {row['requirement']} ({row['node']})")
    else:
        md.append("- None")

    payload = {
        "requirements": len(rows),
        "weighted_progress": score,
        "status_counts": dict(totals),
        "areas": area_json,
        "verify_hw": [r["id"] for r in verify_hw],
        "blocked": [r["id"] for r in blocked],
    }
    return "\n".join(md) + "\n", payload


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--matrix", default="docs/status/EFIS_NEXT_MASTER_MATRIX.md")
    parser.add_argument("--markdown", default="docs/status/EFIS_NEXT_STATUS_GENERATED.md")
    parser.add_argument("--json", default="docs/status/efis-next-status.json")
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()

    matrix = Path(args.matrix)
    markdown_path = Path(args.markdown)
    json_path = Path(args.json)
    rows = parse_matrix(matrix)
    markdown, payload = render(rows)
    json_text = json.dumps(payload, indent=2, sort_keys=True) + "\n"

    if args.check:
        ok = True
        if not markdown_path.exists() or markdown_path.read_text(encoding="utf-8") != markdown:
            print(f"OUTDATED: {markdown_path}")
            ok = False
        if not json_path.exists() or json_path.read_text(encoding="utf-8") != json_text:
            print(f"OUTDATED: {json_path}")
            ok = False
        return 0 if ok else 2

    markdown_path.parent.mkdir(parents=True, exist_ok=True)
    markdown_path.write_text(markdown, encoding="utf-8")
    json_path.write_text(json_text, encoding="utf-8")
    print(f"Generated {markdown_path} and {json_path} from {len(rows)} requirements")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
