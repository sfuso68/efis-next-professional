namespace {

void require(bool condition, const char* message) {
    if (!condition) {
        std::cerr << "FAILED: " << message << '\n';
        std::exit(EXIT_FAILURE);
    }
}

}  // namespace

namespace efis {
struct RecordedSampleLookup final {
    bool present{};
    Sample<double> sample{};
};
}  // namespace efis

namespace {
efis::RecordedSampleLookup find_recorded(
    const std::vector<efis::recording::RecordedSample>& samples,
    efis::SignalId signal) {
    for (const auto& entry : samples) {
        if (entry.sample.origin.signal == signal) return {true, entry.sample};
    }
    return {};
}
}  // namespace

int main() {
    using namespace std::chrono_literals;
    const auto epoch = efis::MonoTime{};

    efis::SimulationProvider first{42};
    efis::SimulationProvider second{42};
    const auto a = first.sample(epoch + 1s, 1s);
    const auto b = second.sample(epoch + 1s, 1s);
    require(a.sequence == b.sequence, "same seed must preserve sequence");
    require(a.attitude.roll_deg.value == b.attitude.roll_deg.value,
            "simulation replay must be deterministic");
    require(a.air_data.indicated_airspeed_kt.validity == efis::Validity::simulated,
            "simulation data must remain explicitly marked");
    require(a.guidance.flight_director_active.value,
            "simulation must exercise flight director");
    require(a.guidance.selected_airspeed_kt.value == 55.0,
            "simulation must publish selected airspeed");
    require(a.navigation.to_flag.value,
            "simulation must publish typed navigation flag");
    efis::SimulationProvider speed_profile{42};
    const auto at_vx = speed_profile.sample(epoch + 16s, 16s);
    const auto at_vy = speed_profile.sample(epoch + 24s, 24s);
    const auto beyond_vne = speed_profile.sample(epoch + 58s, 58s);
    require(std::abs(at_vx.air_data.indicated_airspeed_kt.value - 62.0) < 0.01,
            "simulation profile must expose VX");
    require(std::abs(at_vy.air_data.indicated_airspeed_kt.value - 68.0) < 0.01,
            "simulation profile must expose VY");
    require(beyond_vne.air_data.indicated_airspeed_kt.value > 140.0,
            "simulation profile must exercise VNE warning range");
    efis::EngineSimulationProvider engine_first{84};
    efis::EngineSimulationProvider engine_second{84};
    const auto engine_a = engine_first.sample(epoch + 1s, 1s);
    const auto engine_b = engine_second.sample(epoch + 1s, 1s);
    require(engine_a.rpm.value == engine_b.rpm.value,
            "engine simulation replay must be deterministic");
    require(engine_a.cht_c.size() == 4 && engine_a.egt_c.size() == 4,
            "engine simulation must publish four cylinders");
    require(engine_a.rpm.validity == efis::Validity::simulated,
            "engine values must remain explicitly simulated");
    engine_first.set_fault(efis::engine::EngineFault::low_oil_pressure);
    const auto engine_fault = engine_first.sample(epoch + 2s, 2s);
    require(engine_fault.oil_pressure_psi.value == 22.0,
            "engine fault scenario must drive low oil pressure");
    require(engine_fault.health == efis::engine::EngineHealth::warning,
            "low oil pressure must raise engine warning health");
    efis::FlightModel model{500ms};
    const auto normal = model.normalize(a, epoch + 1s);
    require(!normal.alerts.active.empty(), "normalized simulation must publish advisory state");
    require(normal.alerts.active.front().code == "SIMULATION",
            "simulation advisory must be generated by alert engine");
    auto stale_input = a;
    stale_input.air_data.indicated_airspeed_kt.received_at = epoch;
    const auto stale = model.normalize(stale_input, epoch + 1s);
    require(stale.air_data.indicated_airspeed_kt.validity == efis::Validity::stale,
            "expired sample must be stale");
    require(stale.health.level == efis::HealthLevel::caution,
            "stale data must raise caution health");

    auto missing_input = a;
    missing_input.attitude.heading_deg.validity = efis::Validity::unavailable;
    const auto missing = model.normalize(missing_input, epoch + 1s);
    require(missing.health.level == efis::HealthLevel::warning,
            "unavailable data must raise warning health");

    auto multiple_input = a;
    multiple_input.air_data.indicated_airspeed_kt.validity = efis::Validity::unavailable;
    multiple_input.navigation.cdi_deviation_dots.validity = efis::Validity::unavailable;
    const auto multiple = model.normalize(multiple_input, epoch + 1s);
    require(multiple.alerts.active.size() >= 3,
            "simultaneous faults must retain all active alerts");
    require(multiple.alerts.active.front().code == "AIRSPEED_FAIL",
            "warning must sort ahead of caution and advisory");
    require(multiple.alerts.active[1].code == "NAV_DATA_FAIL",
            "navigation caution must sort ahead of simulation advisory");

    const auto view = efis::display::make_pfd_view(
        normal, efis::display::DisplayProfile::professional);
    require(view.sequence == a.sequence, "display view must preserve sequence");
    require(view.flight_director_active, "PFD must expose valid flight director");
    require(view.alerts.size() == 1, "PFD must preserve active alerts");
    const auto compact_svg = efis::display::SvgPfdRenderer{}.render(view, {800, 480});
    const auto cockpit_svg = efis::display::SvgPfdRenderer{}.render(view, {1920, 1080});
    require(compact_svg.find("viewBox='0 0 800 480'") != std::string::npos,
            "compact renderer must honor resolution");
    require(cockpit_svg.find("viewBox='0 0 1920 1080'") != std::string::npos,
            "cockpit renderer must honor resolution");
    require(compact_svg.find("EFIS") != std::string::npos,
            "renderer must include product identity");

    auto source_sample = [&](double value, efis::SourceId source,
                             efis::Validity validity) {
        return efis::Sample<double>{value, source, epoch, epoch,
                                    efis::Quality::nominal, validity, 1};
    };
    efis::SourceArbitrator<double> arbitrator{{1000ms}};
    std::array candidates{
        source_sample(125.0, efis::SourceId::pixhawk_primary, efis::Validity::valid),
        source_sample(124.0, efis::SourceId::dlvr_legacy, efis::Validity::valid)};
    const auto initial = arbitrator.select(candidates, epoch);
    require(initial.selected.source == efis::SourceId::pixhawk_primary,
            "highest-priority usable source must be selected initially");
    require(initial.change && initial.change->reason == efis::SourceChangeReason::initial,
            "initial selection must emit an event");

    candidates[0].validity = efis::Validity::unavailable;
    const auto failover = arbitrator.select(candidates, epoch + 100ms);
    require(failover.selected.source == efis::SourceId::dlvr_legacy,
            "loss of active source must fail over immediately");
    require(failover.change && failover.change->reason == efis::SourceChangeReason::failover,
            "failover must emit its reason");

    candidates[0].validity = efis::Validity::valid;
    const auto dwell = arbitrator.select(candidates, epoch + 200ms);
    require(dwell.selected.source == efis::SourceId::dlvr_legacy && !dwell.change,
            "recovered primary must respect dwell time");
    const auto reversion = arbitrator.select(candidates, epoch + 1200ms);
    require(reversion.selected.source == efis::SourceId::pixhawk_primary,
            "primary must recover after dwell time");
    require(reversion.change && reversion.change->reason == efis::SourceChangeReason::reversion,
            "reversion must emit its reason");

    std::ostringstream recording_a;
    std::ostringstream recording_b;
    efis::recording::SnapshotRecorder::write_header(recording_a);
    efis::recording::SnapshotRecorder::write_snapshot(recording_a, normal);
    efis::recording::SnapshotRecorder::write_source_change(recording_a,
                                                            *reversion.change);
    efis::recording::SnapshotRecorder::write_header(recording_b);
    efis::recording::SnapshotRecorder::write_snapshot(recording_b, normal);
    efis::recording::SnapshotRecorder::write_source_change(recording_b,
                                                            *reversion.change);
    require(recording_a.str() == recording_b.str(),
            "recorder output must be deterministic");
    require(recording_a.str().find("source_change") != std::string::npos,
            "recorder must preserve source changes");

    const auto test_directory = std::filesystem::temp_directory_path() /
        ("efis-recorder-test-" + std::to_string(
            std::chrono::steady_clock::now().time_since_epoch().count()));
    std::filesystem::create_directories(test_directory);
    {
        efis::recording::SegmentedRecorder segmented{
            test_directory, {.records_per_segment = 2, .flush_every_records = 1}};
        segmented.append(normal);
        segmented.append(normal);
        segmented.append(normal);
        segmented.close();
    }
    std::size_t csv_segments{};
    std::size_t partial_segments{};
    for (const auto& entry : std::filesystem::directory_iterator(test_directory)) {
        csv_segments += entry.path().extension() == ".csv";
        partial_segments += entry.path().extension() == ".partial";
    }
    require(csv_segments == 2, "segment rotation must produce two finalized files");
    require(partial_segments == 0, "clean close must leave no partial segment");

    const auto interrupted = test_directory / "interrupted.partial";
    {
        std::ofstream partial{interrupted};
        partial << "EFIS_RECORDING_V1\n";
    }
    {
        efis::recording::SegmentedRecorder recovered{test_directory};
        require(recovered.recovered_segments() == 1,
                "startup must recover an interrupted nonempty segment");
    }
    require(std::filesystem::exists(test_directory / "interrupted.recovered.csv"),
            "recovered segment must be preserved with an explicit suffix");
    const auto status_path = test_directory / "run" / "recorder.status";
    efis::recording::write_recorder_status(status_path, {
        .state = "RECORDING", .updated_wall_ms = 1234,
        .records = 5678, .segment = "flight-test.partial"});
    const auto recorder_status = efis::recording::read_recorder_status(status_path);
    require(recorder_status.state == "RECORDING",
            "recorder heartbeat must preserve state");
    require(recorder_status.records == 5678,
            "recorder heartbeat must preserve record count");
    require(recorder_status.segment == "flight-test.partial",
            "recorder heartbeat must preserve active segment");
    std::filesystem::remove_all(test_directory);

    // --- Provenienza del campione, paragrafo 17.2 dell'handoff ---------------
    //
    // Ogni campione deve dichiarare quale grandezza trasporta, in quale unita'
    // e se e' simulato. Senza questi dati la black box registra numeri di cui
    // non si potra' piu' ricostruire il significato.
    const auto provenance = efis::SimulationProvider{7}.sample(epoch + 1s, 1s);
    require(provenance.air_data.indicated_airspeed_kt.origin.signal ==
                efis::SignalId::indicated_airspeed,
            "sample must declare which signal it carries");
    require(provenance.air_data.indicated_airspeed_kt.origin.unit == efis::Unit::knot,
            "sample must declare the unit of its engineering value");
    require(provenance.air_data.pressure_altitude_ft.origin.unit == efis::Unit::foot,
            "altitude must be declared in feet, not reused from airspeed");
    require(provenance.navigation.to_flag.origin.unit == efis::Unit::boolean,
            "discrete signals must declare a boolean unit");
    require(provenance.attitude.roll_deg.origin.simulated,
            "simulated data must carry an explicit simulation marker");
    require(provenance.attitude.roll_deg.raw == provenance.attitude.roll_deg.value,
            "simulation applies no conversion, so raw must equal the value");
    require(!provenance.attitude.roll_deg.has_utc(),
            "UTC must stay unavailable while no trusted time source exists");
    require(provenance.attitude.roll_deg.origin.node == efis::node_undeclared,
            "an unassigned node must read as undeclared, not as node zero");

    // Identificativi distinti per cilindri distinti: un CHT registrato sul
    // cilindro sbagliato e' peggio di un CHT mancante.
    const auto cylinders = efis::EngineSimulationProvider{7}.sample(epoch + 1s, 1s);
    require(cylinders.cht_c[0].origin.signal ==
                efis::SignalId::cylinder_head_temperature_1,
            "first cylinder head temperature must map to its own signal");
    require(cylinders.cht_c[3].origin.signal ==
                efis::SignalId::cylinder_head_temperature_4,
            "fourth cylinder head temperature must map to its own signal");
    require(cylinders.egt_c[2].origin.signal ==
                efis::SignalId::exhaust_gas_temperature_3,
            "exhaust gas temperatures must not collide with head temperatures");
    require(cylinders.cht_c[0].origin.unit == efis::Unit::celsius,
            "cylinder temperatures must declare degrees celsius");

    // Un guasto iniettato altera la grandezza misurata, quindi deve alterare
    // anche il valore grezzo: un raw nominale con un value anomalo descrive una
    // conversione sbagliata, che e' un guasto diverso da quello simulato.
    efis::EngineSimulationProvider faulted{7};
    faulted.set_fault(efis::engine::EngineFault::low_oil_pressure);
    const auto with_fault = faulted.sample(epoch + 1s, 1s);
    require(with_fault.oil_pressure_psi.value == 22.0,
            "injected fault must reach the engineering value");
    require(with_fault.oil_pressure_psi.raw == 22.0,
            "injected fault must reach the raw value as well");

    // --- Il marcatore di simulazione sopravvive all'invecchiamento -----------
    //
    // Prima di questa regola un campione simulato che scadeva diventava
    // semplicemente STALE, indistinguibile da un dato reale scaduto. Il
    // paragrafo 19 vieta che un valore simulato possa presentarsi come reale.
    efis::FlightModel ageing_model{200ms};
    auto ageing_input = efis::SimulationProvider{7}.sample(epoch + 1s, 1s);
    const auto aged = ageing_model.normalize(ageing_input, epoch + 5s);
    require(aged.air_data.indicated_airspeed_kt.validity == efis::Validity::stale,
            "an old sample must be marked stale");
    require(aged.air_data.indicated_airspeed_kt.is_simulated(),
            "a stale simulated sample must still be recognisable as simulated");

    const auto aged_view = efis::display::make_pfd_view(
        aged, efis::display::DisplayProfile::professional);
    require(aged_view.airspeed_kt.simulated,
            "the display must carry the simulation marker through staleness");
    require(std::string{efis::display::field_label(aged_view.airspeed_kt)} == "SIM STALE",
            "a stale simulated field must declare both conditions");
    const efis::display::DisplayField real_stale{120.0, efis::Validity::stale,
                                                 efis::SourceId::pixhawk_primary, false};
    require(std::string{efis::display::field_label(real_stale)} == "STALE",
            "a real stale field must not be labelled as simulated");
    const auto aged_svg = efis::display::SvgPfdRenderer{}.render(aged_view, {1024, 600});
    require(aged_svg.find("SIM STALE") != std::string::npos,
            "the rendered PFD must show that the value is both simulated and stale");

    // Nomi e simboli sono le intestazioni della black box: se cambiano, le
    // registrazioni precedenti diventano illeggibili.
    require(std::string{efis::signal_name(efis::SignalId::oil_temperature)} ==
                "oil_temperature",
            "signal names must stay stable for recorded data");
    require(std::string{efis::unit_symbol(efis::Unit::foot_per_minute)} == "fpm",
            "unit symbols must stay stable for recorded data");
    require(efis::sample_schema_version == 2,
            "sample schema version must match Display Data Protocol V2");

    // --- Salute dei nodi, paragrafi 6 e 17.1 dell'handoff --------------------
    //
    // Un nodo dichiarato e mai sentito non e' un nodo perduto. Confondere le due
    // condizioni in una sola spia toglie al pilota l'informazione che serve:
    // "mai sentito" indica cablaggio assente o nodo spento, "perso" indica un
    // guasto sopravvenuto.
    efis::NodeHealthMonitor monitor{{.stale_after = 1000ms, .lost_after = 3000ms}};
    constexpr efis::NodeId engine_node = 21;
    constexpr efis::NodeId absent_node = 99;
    monitor.declare(engine_node);
    monitor.declare(absent_node);
    require(monitor.status(engine_node)->state == efis::NodeState::unknown,
            "a declared node must start as unknown, never as online");
    require(!monitor.all_online(),
            "a node never heard from must prevent an all-online verdict");

    require(monitor.update(epoch + 10s).empty(),
            "a node never heard from must not be reported as lost");
    require(monitor.status(absent_node)->state == efis::NodeState::unknown,
            "silence cannot lose what was never present");

    require(monitor.heartbeat(engine_node, epoch + 1s, 1) ==
                efis::HeartbeatVerdict::accepted,
            "the first heartbeat must be accepted");
    require(monitor.status(engine_node)->state == efis::NodeState::online,
            "a node that has just reported must be online");

    // Un battito scartato non deve rinviare il timeout. Un nodo bloccato che
    // ripete all'infinito lo stesso messaggio deve invecchiare come un nodo
    // muto: e' il motivo per cui contare i battiti non basta e serve la
    // sequenza.
    require(monitor.heartbeat(engine_node, epoch + 2s, 1) ==
                efis::HeartbeatVerdict::duplicate,
            "a repeated sequence must be recognised as a duplicate");
    require(monitor.heartbeat(engine_node, epoch + 2s, 0) ==
                efis::HeartbeatVerdict::regressed,
            "a sequence going backwards must be recognised as a regression");
    require(!efis::accepts_data(efis::HeartbeatVerdict::duplicate),
            "duplicated frames must not be used as data");
    require(!efis::accepts_data(efis::HeartbeatVerdict::regressed),
            "regressed frames must not be used as data");
    require(monitor.status(engine_node)->last_accepted == epoch + 1s,
            "a discarded heartbeat must not refresh the timeout");

    const auto stale_changes = monitor.update(epoch + 2500ms);
    require(stale_changes.size() == 1, "only the silent node must change state");
    require(stale_changes.front().node == engine_node &&
                stale_changes.front().previous == efis::NodeState::online &&
                stale_changes.front().current == efis::NodeState::stale,
            "a stuck node repeating its last frame must still go stale");
    require(!efis::is_usable(efis::NodeState::stale),
            "data from a stale node must not be treated as usable");

    const auto lost_changes = monitor.update(epoch + 5s);
    require(lost_changes.size() == 1 &&
                lost_changes.front().current == efis::NodeState::lost,
            "continued silence must escalate from stale to lost");
    require(monitor.update(epoch + 6s).empty(),
            "a state that has not changed must not emit a repeated event");

    // Il ritorno di un nodo e' un evento quanto la sua perdita: la black box
    // deve poter ricostruire l'intera sequenza.
    require(monitor.heartbeat(engine_node, epoch + 7s, 2) ==
                efis::HeartbeatVerdict::accepted,
            "a returning node must be accepted again");
    require(monitor.status(engine_node)->state == efis::NodeState::online,
            "a returning node must come back online immediately");
    require(monitor.update(epoch + 7s).empty(),
            "the recovery is already recorded by the accepted heartbeat");

    // I salti di sequenza misurano i messaggi persi, non gli episodi.
    require(monitor.heartbeat(engine_node, epoch + 8s, 6) ==
                efis::HeartbeatVerdict::accepted_after_gap,
            "a sequence jump must be accepted but reported as a gap");
    require(monitor.status(engine_node)->missed == 3,
            "the gap must count the messages actually missing");
    require(efis::accepts_data(efis::HeartbeatVerdict::accepted_after_gap),
            "data after a gap is still usable, the loss is only recorded");

    // Un nodo che si presenta senza essere stato dichiarato va comunque
    // seguito: e' un'anomalia da mostrare, non da sopprimere.
    efis::NodeHealthMonitor discovery{};
    require(discovery.heartbeat(77, epoch + 1s, 1) == efis::HeartbeatVerdict::accepted,
            "an undeclared node appearing on the bus must be tracked");
    require(discovery.status(77).has_value(),
            "an undeclared node must become visible, not be ignored");
    require(std::string{efis::node_state_name(efis::NodeState::lost)} == "LOST",
            "node state names must stay stable for recorded data");

    // --- Parser MAVLink, verificato su frame di riferimento ------------------
    //
    // I byte provengono da pymavlink, l'implementazione di riferimento, e non da
    // questo progetto: se il parser li interpreta correttamente lo fa perche'
    // rispetta il protocollo, non perche' condivide un malinteso con i test.
    // Vedi tools/mavlink/generate_test_vectors.py.
    namespace reference = efis::mavlink::reference;

    auto drain = [](efis::mavlink::Parser& parser, const std::uint8_t* bytes,
                    std::size_t count) {
        parser.push(std::span<const std::uint8_t>(bytes, count));
        std::vector<efis::mavlink::Frame> frames;
        while (auto frame = parser.next()) frames.push_back(*frame);
        return frames;
    };
    auto single = [&drain](const std::uint8_t* bytes, std::size_t count) {
        efis::mavlink::Parser parser;
        const auto frames = drain(parser, bytes, count);
        require(frames.size() == 1, "a reference stream must yield exactly one frame");
        return frames.front();
    };
    auto value = [](const efis::mavlink::Frame& frame, std::string_view name,
                    std::size_t index = 0) {
        const auto* definition = efis::mavlink::find_message(frame.message_id);
        require(definition != nullptr, "a decoded frame must be in the message table");
        return efis::mavlink::read_field(*definition, frame, name, index);
    };
    auto close_to = [](double got, double expected) {
        return std::abs(got - expected) < 1e-4;
    };

    const auto attitude = single(reference::attitude, std::size(reference::attitude));
    require(attitude.message_id == 30, "ATTITUDE must be identified by its id");
    require(attitude.version2, "the reference frame is MAVLink 2");
    require(close_to(value(attitude, "roll").value, -0.5235988),
            "a negative float field must survive decoding");
    require(close_to(value(attitude, "pitch").value, 0.1745329),
            "field offsets must follow the wire order, not the declaration order");
    require(close_to(value(attitude, "yaw").value, 1.5707963),
            "the last field of the payload must decode correctly");
    require(value(attitude, "time_boot_ms").value == 123456.0,
            "an unsigned field must decode exactly");
    require(value(attitude, "nonexistent_field").status ==
                efis::mavlink::FieldStatus::unknown_field,
            "a field the message does not define must be reported as unknown");

    // Percorso del sensore aria. VFR_HUD porta la velocita' gia' calcolata.
    const auto hud = single(reference::vfr_hud, std::size(reference::vfr_hud));
    require(close_to(value(hud, "airspeed").value, 32.5),
            "indicated airspeed must decode");
    require(close_to(value(hud, "climb").value, -2.5),
            "a negative vertical speed must decode");
    require(value(hud, "heading").value == 42.0,
            "a small integer packed among floats must keep its offset");

    // SCALED_PRESSURE porta la pressione differenziale grezza e la temperatura.
    const auto pressure = single(reference::scaled_pressure,
                                 std::size(reference::scaled_pressure));
    require(close_to(value(pressure, "press_abs").value, 1013.25),
            "absolute pressure must decode");
    require(close_to(value(pressure, "press_diff").value, 0.1718),
            "the differential pressure of the air data sensor must decode");
    require(value(pressure, "temperature").value == 2350.0,
            "sensor temperature must decode as a signed integer");

    // AIRSPEED e' il messaggio dedicato al sensore aria: pressione grezza,
    // temperatura dell'elemento e flag di stato. E' il contenuto che permette di
    // sfruttare il Matek ASPD-DLVR oltre alla sola velocita' calcolata, e la
    // ragione per cui la tabella comprende anche messaggi che il dialetto
    // stabile di pymavlink non definisce ancora.
    const auto airspeed = single(reference::airspeed, std::size(reference::airspeed));
    require(airspeed.message_id == 295, "AIRSPEED must be identified by its id");
    require(close_to(value(airspeed, "airspeed").value, 8.33),
            "the computed airspeed must decode");
    require(close_to(value(airspeed, "raw_press").value, 17.18),
            "the raw differential pressure must decode: it is the actual measurement");
    require(value(airspeed, "temperature").value == 2415.0,
            "the sensing element temperature must decode");
    require(value(airspeed, "id").value == 0.0,
            "the sensor instance must decode, so several sensors stay distinct");
    require(value(airspeed, "flags").ok(),
            "the sensor status flags must be readable");

    // Maschere a 32 bit: perdere un bit significa perdere lo stato di un sensore.
    const auto status = single(reference::sys_status, std::size(reference::sys_status));
    require(value(status, "onboard_control_sensors_present").value ==
                static_cast<double>(0x1400002FU),
            "the sensor presence mask must decode bit for bit");
    require(value(status, "onboard_control_sensors_health").value ==
                static_cast<double>(0x1400000FU),
            "the sensor health mask must decode bit for bit");

    // Tempo a 64 bit. Resta esatto perche' sotto i 2^53 rappresentabili.
    const auto system_time = single(reference::system_time,
                                    std::size(reference::system_time));
    require(value(system_time, "time_unix_usec").value == 1755739800000000.0,
            "a 64 bit timestamp must decode without loss");

    // Zeri finali rimossi. Il satellitare senza fix trasmette zero satelliti e
    // MAVLink 2 elimina quel byte: il campo sta nella parte base del messaggio,
    // quindi vale davvero zero e va letto come tale.
    const auto no_fix = single(reference::gps_no_fix, std::size(reference::gps_no_fix));
    const auto* gps_definition = efis::mavlink::find_message(24);
    require(no_fix.payload_length < gps_definition->length,
            "the reference frame must actually exercise trailing zero removal");
    require(value(no_fix, "fix_type").value == 1.0, "the fix type must decode");
    require(value(no_fix, "satellites_visible").ok(),
            "a trimmed base field is present, not missing");
    require(value(no_fix, "satellites_visible").value == 0.0,
            "a trimmed base field is genuinely zero and must read as zero");

    // Campi di estensione mai trasmessi. Qui la differenza conta: `yaw` sta
    // oltre la parte base, quindi la sua assenza significa che il trasmettitore
    // non lo conosce. Restituirlo come zero direbbe che l'orientamento e' nord,
    // che e' un dato inventato.
    const auto fix = single(reference::gps_fix_3d, std::size(reference::gps_fix_3d));
    require(value(fix, "fix_type").value == 3.0, "a three dimensional fix must decode");
    require(value(fix, "satellites_visible").value == 14.0,
            "the satellite count must decode");
    require(value(fix, "lat").value == 456484000.0,
            "latitude must decode as a signed integer");
    require(fix.payload_length <= gps_definition->base_length,
            "the reference sender must not transmit the extension fields");
    require(value(fix, "yaw").status == efis::mavlink::FieldStatus::not_transmitted,
            "an extension field never transmitted must be absent, not zero");
    require(value(fix, "h_acc").status == efis::mavlink::FieldStatus::not_transmitted,
            "accuracy extensions must not be invented when absent");

    // Testo in un campo di caratteri, non necessariamente terminato.
    const auto text_frame = single(reference::statustext,
                                   std::size(reference::statustext));
    require(efis::mavlink::read_text(*efis::mavlink::find_message(253), text_frame,
                                     "text") == "PreArm: GPS bad fix",
            "a character field must decode as text");

    // MAVLink 1: intestazione diversa, stesso contenuto.
    efis::mavlink::Parser legacy_parser;
    const auto legacy = drain(legacy_parser, reference::attitude_v1,
                              std::size(reference::attitude_v1)).front();
    require(!legacy.version2, "a MAVLink 1 frame must be recognised as such");
    require(close_to(value(legacy, "roll").value, -0.5235988),
            "MAVLink 1 must decode to the same values as MAVLink 2");
    require(legacy_parser.statistics().frames_v1 == 1,
            "MAVLink 1 frames must be counted separately");

    // Frame firmato: i tredici byte di firma vanno consumati, altrimenti
    // verrebbero letti come inizio del messaggio successivo. Il frame che segue
    // dimostra che non e' accaduto.
    efis::mavlink::Parser signed_parser;
    const auto signed_frames = drain(signed_parser, reference::heartbeat_signed,
                                     std::size(reference::heartbeat_signed));
    require(signed_frames.size() == 1, "the signed frame must be accepted");
    require(signed_frames.front().signed_frame,
            "a signed frame must be reported as signed, not silently trusted");
    const auto after_signature = drain(signed_parser, reference::attitude,
                                       std::size(reference::attitude));
    require(after_signature.size() == 1,
            "the signature must be consumed so the next frame still parses");

    // Payload interamente azzerato. MAVLink 2 ne conserva comunque un byte, mai
    // meno, quindi il primo campo arriva tagliato a meta'.
    const auto ref_trimmed = single(reference::power_status_trimmed,
                                std::size(reference::power_status_trimmed));
    require(ref_trimmed.payload_length == 1,
            "an all zero payload is trimmed to the single byte the protocol keeps");
    require(value(ref_trimmed, "Vcc").value == 0.0,
            "a base field received only in part must be completed with zeros");

    // Un frame consegnato un byte alla volta deve dare lo stesso risultato di uno
    // consegnato tutto insieme: leggendo da una seriale i confini non si
    // scelgono.
    efis::mavlink::Parser dribbled_parser;
    std::vector<efis::mavlink::Frame> dribbled;
    for (const std::uint8_t byte : reference::attitude) {
        const auto batch = drain(dribbled_parser, &byte, 1);
        dribbled.insert(dribbled.end(), batch.begin(), batch.end());
    }
    require(dribbled.size() == 1,
            "a frame split across reads must still be assembled");
    require(close_to(value(dribbled.front(), "roll").value, -0.5235988),
            "a frame split across reads must decode identically");

    // Robustezza del flusso. Rumore prima di un frame valido: va scartato e
    // contato, e il frame va comunque trovato.
    efis::mavlink::Parser ref_noisy_parser;
    const std::uint8_t ref_noise[] = {0x00, 0xFF, 0x12, 0xAB};
    drain(ref_noisy_parser, ref_noise, std::size(ref_noise));
    const auto recovered = drain(ref_noisy_parser, reference::attitude,
                                 std::size(reference::attitude));
    require(recovered.size() == 1,
            "the parser must resynchronise after noise on the line");
    require(ref_noisy_parser.statistics().dropped_bytes == std::size(ref_noise),
            "discarded bytes must be counted, not silently ignored");

    // Falso avvio: un byte di inizio frame comparso per caso nel rumore. Il
    // parser legge come lunghezza il byte che segue e attende un messaggio che
    // non arrivera' mai; solo quando ha abbastanza dati puo' verificare il
    // checksum, scoprire che non torna e ripartire dal byte successivo.
    //
    // L'episodio costa quindi i dati che stavano dentro quella lunghezza
    // fittizia, non un singolo byte. E' il comportamento di MAVLink e non c'e'
    // modo di fare meglio senza fidarsi di un campo non verificato. Cio' che
    // deve essere garantito, ed e' quello che si verifica qui, e' che la
    // sincronia venga riacquistata da sola.
    efis::mavlink::Parser false_start_parser;
    const std::uint8_t false_start[] = {0xFD};
    drain(false_start_parser, false_start, std::size(false_start));
    std::vector<efis::mavlink::Frame> after_false_start;
    for (int repeat = 0; repeat < 10; ++repeat) {
        const auto batch = drain(false_start_parser, reference::attitude,
                                 std::size(reference::attitude));
        after_false_start.insert(after_false_start.end(), batch.begin(), batch.end());
    }
    require(!after_false_start.empty(),
            "after a false frame start the parser must regain synchronisation");
    require(close_to(value(after_false_start.front(), "roll").value, -0.5235988),
            "the frames recovered after a false start must decode correctly");

    // Frame corrotto: un solo byte del payload alterato deve far fallire il
    // controllo, non produrre un valore leggermente sbagliato.
    efis::mavlink::Parser ref_corrupt_parser;
    std::vector<std::uint8_t> ref_corrupted(std::begin(reference::attitude),
                                        std::end(reference::attitude));
    ref_corrupted[12] = static_cast<std::uint8_t>(ref_corrupted[12] ^ 0x40);
    const auto ref_corrupt_frames = drain(ref_corrupt_parser, ref_corrupted.data(), ref_corrupted.size());
    require(ref_corrupt_frames.empty(),
            "a corrupted frame must be rejected, never delivered");
    require(ref_corrupt_parser.statistics().crc_errors >= 1,
            "the checksum failure must be recorded");

    // Messaggio non presente in tabella: senza il suo CRC_EXTRA il checksum non
    // e' calcolabile, quindi il frame non e' verificabile e non viene consegnato.
    efis::mavlink::Parser ref_unknown_parser;
    std::vector<std::uint8_t> unknown(std::begin(reference::attitude),
                                      std::end(reference::attitude));
    unknown[7] = 0xFE;
    const auto ref_unknown_frames = drain(ref_unknown_parser, unknown.data(), unknown.size());
    require(ref_unknown_frames.empty(), "an unverifiable message must not be delivered");
    require(ref_unknown_parser.statistics().unknown_messages >= 1,
            "unknown messages must be counted");

    // La tabella generata deve conservare i valori del protocollo.
    require(efis::mavlink::find_message(30)->crc_extra == 39,
            "ATTITUDE keeps its protocol defined CRC_EXTRA");
    require(efis::mavlink::find_message(295)->crc_extra == 234,
            "AIRSPEED keeps the CRC_EXTRA the reference implementation computes");
    require(gps_definition->base_length == 30,
            "GPS_RAW_INT base length must exclude the extension fields");
    require(gps_definition->length == 52,
            "GPS_RAW_INT full length must include the extension fields");
    require(efis::mavlink::find_message(999999) == nullptr,
            "an unknown message id must not resolve to a definition");

    // --- Il parser contro l'hardware vero ------------------------------------
    //
    // Le prove precedenti usano frame prodotti da pymavlink: dimostrano che il
    // parser rispetta il protocollo. Questa usa 68 kB registrati in ascolto
    // passivo dal Pixhawk 6X il 21 agosto 2026, senza trasmettere un solo byte
    // verso il controllore. Dimostra una cosa diversa e non deducibile dalla
    // prima: che il parser regge cio' che ArduPlane 4.7.0 emette davvero, con il
    // suo rumore, i suoi troncamenti e i suoi messaggi.
    auto definition_of = [](const efis::mavlink::Frame& frame) {
        const auto* found = efis::mavlink::find_message(frame.message_id);
        require(found != nullptr, "a delivered frame must be in the message table");
        return found;
    };

    const std::filesystem::path capture_path =
        std::filesystem::path{EFIS_TEST_DATA_DIR} / "mavlink" /
        "arduplane-4.7.0-usb-20260821.mav";
    require(std::filesystem::exists(capture_path),
            "the reference capture must be available to the tests");

    std::ifstream capture_file{capture_path, std::ios::binary};
    const std::vector<char> capture{std::istreambuf_iterator<char>{capture_file},
                                    std::istreambuf_iterator<char>{}};
    require(capture.size() == 68443, "the reference capture must be intact");

    efis::mavlink::Parser recorded;
    std::map<std::uint32_t, std::uint64_t> seen;
    std::map<std::uint32_t, efis::mavlink::Frame> first_of;
    for (char raw : capture) {
        const auto byte = static_cast<std::uint8_t>(raw);
        recorded.push(std::span<const std::uint8_t>(&byte, 1));
        while (const auto frame = recorded.next()) {
            ++seen[frame->message_id];
            first_of.try_emplace(frame->message_id, *frame);
        }
    }

    // Il conto torna esattamente. La registrazione contiene 2159 frame: il
    // parser ne consegna 2157 e ne rifiuta 2, PARAM_VALUE e TIMESYNC, che non
    // sono in tabella e il cui checksum non e' quindi calcolabile. Non ne perde
    // nessun altro e non ne inventa nessuno.
    require(recorded.statistics().frames == 2157,
            "the parser must recover every verifiable frame of the capture");
    require(recorded.statistics().unknown_messages == 2,
            "the two messages outside the table must be refused, not guessed");
    require(recorded.statistics().crc_errors == 0,
            "a clean USB link must not produce a single checksum failure");
    require(seen.size() == 27, "every message type of the capture must be decoded");
    require(seen[0] == 9, "HEARTBEAT count must match the reference decode");
    require(seen[30] == 85, "ATTITUDE count must match the reference decode");
    require(seen[24] == 86, "GPS_RAW_INT count must match the reference decode");

    // Assetto, confrontato con la decodifica di pymavlink sugli stessi byte.
    const auto& attitude_real = first_of.at(30);
    require(close_to(*efis::mavlink::read_number(*definition_of(attitude_real), attitude_real, "roll"), -0.167344913),
            "ATTITUDE roll must match the reference decode of the same bytes");
    require(close_to(*efis::mavlink::read_number(*definition_of(attitude_real), attitude_real, "pitch"), 0.182977259),
            "ATTITUDE pitch must match the reference decode of the same bytes");

    // --- Il sensore aria ------------------------------------------------------
    //
    // AIRSPEED (295) e' il messaggio dedicato al sensore. La versione di
    // pymavlink usata come riferimento non lo conosce e lo scarta come dato
    // illeggibile: la sua definizione e' scritta nel progetto. Che tutti i frame
    // superino il checksum lo dimostra esatto, perche' una sola parola sbagliata
    // fra nomi e tipi produrrebbe un CRC_EXTRA diverso e li farebbe rifiutare
    // tutti quanti.
    require(efis::mavlink::find_message(295) != nullptr,
            "AIRSPEED must be present in the message table");
    require(efis::mavlink::find_message(295)->crc_extra == 234,
            "the AIRSPEED CRC_EXTRA must be the one the real frames validate with");
    require(seen[295] == 85, "every AIRSPEED frame in the capture must be accepted");

    const auto& airspeed_real = first_of.at(295);
    require(airspeed_real.payload_length == 10,
            "the real AIRSPEED frames arrive with their trailing zeros removed");
    require(close_to(*efis::mavlink::read_number(*definition_of(airspeed_real), airspeed_real, "airspeed"), 0.430416673),
            "the airspeed computed by the autopilot must decode");
    require(close_to(*efis::mavlink::read_number(*definition_of(airspeed_real), airspeed_real, "raw_press"), 0.0949074),
            "the raw differential pressure must decode: it is what the sensor measures");
    require(*efis::mavlink::read_integer(*definition_of(airspeed_real), airspeed_real, "temperature") == 3385,
            "the temperature of the sensing element must decode");
    require(*efis::mavlink::read_integer(*definition_of(airspeed_real), airspeed_real, "flags") == 0,
            "flags were removed as a trailing zero and really are zero");

    // Lo stesso sensore compare in SCALED_PRESSURE, dove la temperatura
    // dell'elemento differenziale e' un campo di estensione realmente
    // trasmesso: deve risultare presente, e deve concordare con AIRSPEED.
    const auto& pressure_real = first_of.at(29);
    const auto element_temperature =
        efis::mavlink::read_integer(*definition_of(pressure_real), pressure_real, "temperature_press_diff");
    require(element_temperature.has_value(),
            "a transmitted extension must be read, not treated as absent");
    require(*element_temperature == 3385,
            "the two messages must agree on the temperature of the same element");

    // Il sensore e' presente e misura, ma il controllo di volo lo dichiara non
    // sano, coerentemente con ARSPD_USE a zero. Il dato grezzo va registrato, la
    // velocita' che ne deriva non va presentata come valida: e' il caso reale su
    // cui il paragrafo 19 dell'handoff non ammette scorciatoie.
    constexpr std::uint64_t differential_pressure_bit = 0x20;
    const auto& sys_status_real = first_of.at(1);
    const auto present_mask =
        *efis::mavlink::read_unsigned(*definition_of(sys_status_real), sys_status_real, "onboard_control_sensors_present");
    const auto health_mask =
        *efis::mavlink::read_unsigned(*definition_of(sys_status_real), sys_status_real, "onboard_control_sensors_health");
    require((present_mask & differential_pressure_bit) != 0,
            "the differential pressure sensor must be reported as present");
    require((health_mask & differential_pressure_bit) == 0,
            "the recorded state has the differential pressure sensor unhealthy");

    // Stato reale del satellitare al momento della registrazione: comunicante,
    // senza fix. Il paragrafo 13 impone di trattare come invalide le coordinate
    // ricevute in questa condizione.
    const auto& gps_real = first_of.at(24);
    require(*efis::mavlink::read_integer(*definition_of(gps_real), gps_real, "fix_type") == 1,
            "the recorded GNSS state must still be no fix");
    require(*efis::mavlink::read_integer(*definition_of(gps_real), gps_real, "satellites_visible") == 0,
            "the recorded GNSS state must still report zero satellites");
    require(*efis::mavlink::read_integer(*definition_of(gps_real), gps_real, "lat") == 0,
            "without a fix the reported position is not a position");

    // Il tempo UTC non e' ancora affidabile: senza fix il controllore non ha una
    // sorgente di tempo, e lo dichiara con uno zero. Va propagato come assenza,
    // non come istante zero.
    require(*efis::mavlink::read_unsigned(*definition_of(first_of.at(2)), first_of.at(2), "time_unix_usec") == 0,
            "without a GNSS fix the autopilot declares UTC as unavailable");

    require(efis::mavlink::read_text(*definition_of(first_of.at(253)), first_of.at(253), "text") ==
                "PreArm: Hardware safety switch",
            "the recorded pre-arm warning must decode as text");

    // --- Adapter MAVLink: dai frame ai campioni ------------------------------
    //
    // L'adapter e' alimentato con la stessa registrazione reale, byte per byte,
    // come se arrivasse dalla seriale. Cio' che si verifica qui non e' la
    // decodifica, gia' provata sopra, ma le regole di validita': senza di esse
    // un valore verrebbe mostrato per il solo fatto di essere arrivato.
    efis::MavlinkAdapter adapter{{.stale_after = 1000ms, .lost_after = 3000ms}};
    const auto arrival = epoch + 1s;
    for (std::size_t offset = 0; offset < capture.size(); offset += 512) {
        const std::size_t count = std::min<std::size_t>(512, capture.size() - offset);
        adapter.consume(
            std::span<const std::uint8_t>(
                reinterpret_cast<const std::uint8_t*>(capture.data()) + offset, count),
            arrival);
    }

    require(adapter.statistics().frames_applied > 500,
            "the adapter must translate the messages it covers");
    require(adapter.parser_statistics().crc_errors == 0,
            "the adapter must not introduce decoding errors of its own");

    // Assetto: il valore ingegneristico e' in gradi perche' e' cosi' che si
    // mostra, il grezzo resta in radianti come il sensore lo emette. Conservare
    // entrambi permette di rifare la conversione senza ripetere la prova.
    const auto& attitude_sample = adapter.snapshot().attitude.roll_deg;
    require(attitude_sample.origin.unit == efis::Unit::degree,
            "attitude must be published in degrees");
    require(std::abs(attitude_sample.raw) < 3.15,
            "the raw value must keep the radians the sensor emitted");
    require(close_to(attitude_sample.value, attitude_sample.raw * 57.295779513),
            "the engineering value must be the same angle expressed in degrees");
    require(attitude_sample.raw != attitude_sample.value,
            "a converted value must not be confused with the raw measurement");
    require(attitude_sample.source == efis::SourceId::pixhawk_primary,
            "data from the flight controller must declare its source");
    require(!attitude_sample.is_simulated(),
            "real data must never be marked as simulated");
    require(attitude_sample.origin.node != efis::node_undeclared,
            "a sample must declare which node produced it");

    // Posizione senza fix tridimensionale. Il paragrafo 13 dell'handoff impone
    // di ignorare le coordinate ricevute in questa condizione: non basta che
    // siano arrivate.
    const auto& latitude = adapter.snapshot().position.latitude_deg;
    require(latitude.origin.signal == efis::SignalId::latitude,
            "the position sample must be published");
    require(latitude.validity == efis::Validity::unavailable,
            "without a three dimensional fix a position is not a position");
    require(!latitude.usable(),
            "no consumer may use a position received without a fix");
    require(adapter.snapshot().position.ground_speed_kt.validity ==
                efis::Validity::unavailable,
            "ground speed derived from the satellite receiver falls with it");

    // Il tempo UTC non e' affidabile e resta dichiarato assente, non datato al
    // 1970.
    require(!attitude_sample.has_utc(),
            "UTC must stay unavailable while the autopilot declares no time source");

    // Il sensore aria. Il controllo di volo lo dichiara presente ma non sano,
    // coerentemente con ARSPD_USE a zero: dal solo bit non si distingue "non
    // usato" da "guasto", quindi la velocita' che ne deriva non e' presentabile.
    const auto& air = adapter.air_data_sensor();
    require(air.declared_present, "the differential pressure sensor is present");
    require(!air.declared_healthy,
            "the recorded state has the sensor declared unhealthy");
    require(air.computed_airspeed_kt.validity == efis::Validity::unavailable,
            "an airspeed derived from a sensor declared unhealthy is not valid");
    require(adapter.snapshot().air_data.indicated_airspeed_kt.validity ==
                efis::Validity::unavailable,
            "the same rule must reach the flight snapshot the display reads");

    // La grandezza misurata resta invece valida, ed e' il punto: al banco serve
    // la pressione, non la velocita' che il controllo di volo ne ricava.
    require(air.differential_pressure_hpa.validity == efis::Validity::valid,
            "the measured differential pressure stays usable at the bench");
    require(air.differential_pressure_hpa.origin.unit == efis::Unit::hectopascal,
            "the differential pressure must declare its unit");
    require(air.differential_pressure_hpa.raw == air.differential_pressure_hpa.value,
            "the pressure needs no conversion, so raw and value must coincide");
    require(std::abs(air.differential_pressure_hpa.value) < 5.0,
            "with the aircraft at rest the differential pressure must stay near zero");
    require(close_to(air.element_temperature_c.value,
                     air.element_temperature_c.raw / 100.0),
            "the temperature must be published in celsius, the wire carries hundredths");
    require(air.element_temperature_c.value > 20.0 &&
                air.element_temperature_c.value < 60.0,
            "the recorded element temperature must stay in a plausible bench range");
    require(air.element_temperature_c.origin.unit == efis::Unit::celsius,
            "the temperature must declare its unit");

    // Salute dei nodi. Il Pixhawk si presenta come sistema e componente: due
    // componenti dello stesso sistema sono due sorgenti distinte.
    const auto autopilot = efis::MavlinkAdapter::node_of(1, 1);
    require(adapter.health().status(autopilot).has_value(),
            "the autopilot must be tracked as a node");
    require(adapter.health().status(autopilot)->state == efis::NodeState::online,
            "a node that has just been heard must be online");

    // Il contatore di sequenza MAVLink e' a otto bit e si azzera ogni 256
    // messaggi. Interpretarlo alla lettera farebbe apparire una regressione a
    // ogni giro, cioe' un guasto inesistente ogni due secondi e mezzo.
    require(adapter.statistics().sequence_wraps > 5,
            "the capture must actually exercise the eight bit sequence wrap");
    require(adapter.health().status(autopilot)->regressions == 0,
            "a wrapping sequence counter must not be read as a fault");

    // Il silenzio deve produrre un evento anche senza dati in arrivo.
    adapter.update(arrival + 5s);
    require(!adapter.node_events().empty(),
            "prolonged silence must produce a node state change");
    require(adapter.node_events().back().current == efis::NodeState::lost,
            "a node silent beyond the timeout must be declared lost");
    require(adapter.last_status_text() != "",
            "the pre-arm warning from the flight controller must be retained");

    // --- Registro di volo V2: andata e ritorno -------------------------------
    //
    // Il paragrafo 17.3 dell'handoff chiede replay deterministico. Il formato V1
    // non aveva un lettore, quindi la domanda non si poteva nemmeno porre: cio'
    // che veniva scritto non veniva mai riletto, e nessuno poteva accorgersi che
    // registrava tre segnali su venti e nessuna provenienza.
    efis::FlightSnapshot recorded_input = efis::SimulationProvider{11}.sample(
        epoch + 3s, 3s);
    // Provenienza completa su un campione, come la produrrebbe un nodo reale.
    auto& ias_sample = recorded_input.air_data.indicated_airspeed_kt;
    ias_sample.origin.node = 4097;
    ias_sample.origin.channel = 7;
    ias_sample.origin.calibration_revision = 42;
    ias_sample.utc = 1755739800123456ULL;
    ias_sample.quality = efis::Quality::nominal;
    ias_sample.raw = 17.181411743164062;

    std::ostringstream written;
    efis::recording::FlightRecordWriter::write_header(written);
    efis::recording::FlightRecordWriter::write_snapshot(written, recorded_input);
    efis::recording::FlightRecordWriter::write_node_event(
        written, {4097, efis::NodeState::online, efis::NodeState::stale, epoch + 4s});
    efis::recording::FlightRecordWriter::write_source_change(
        written, {efis::SourceId::simulation, efis::SourceId::pixhawk_primary,
                  efis::SourceChangeReason::failover, epoch + 5s});

    std::istringstream to_read{written.str()};
    const auto replayed = efis::recording::read_flight_record(to_read);
    require(replayed.schema == 2, "the record must declare its schema");
    require(replayed.malformed_rows == 0, "a record just written must be readable");
    require(replayed.samples.size() == 16,
            "every signal of the snapshot must be recorded, not only three");
    require(replayed.node_events.size() == 1, "node events must survive the round trip");
    require(replayed.source_changes.size() == 1,
            "source changes must survive the round trip");

    const efis::RecordedSampleLookup found = find_recorded(
        replayed.samples, efis::SignalId::indicated_airspeed);
    require(found.present, "the recorded airspeed must be found by its signal");
    const auto& back = found.sample;
    require(back.origin.signal == efis::SignalId::indicated_airspeed,
            "the signal identity must survive");
    require(back.origin.node == 4097, "the producing node must survive");
    require(back.origin.channel == 7, "the channel must survive");
    require(back.origin.unit == efis::Unit::knot, "the unit must survive");
    require(back.origin.calibration_revision == 42,
            "the calibration revision must survive: without it a recording cannot "
            "be compared with another taken under a different tuning");
    require(back.origin.simulated, "the simulation marker must survive");
    require(back.utc == 1755739800123456ULL,
            "a 64 bit UTC timestamp must survive without loss");
    require(back.quality == efis::Quality::nominal, "the quality must survive");
    require(back.validity == efis::Validity::simulated, "the validity must survive");
    require(back.sequence == recorded_input.sequence ||
                back.sequence == ias_sample.sequence,
            "the sequence counter must survive");

    // Precisione. V1 scriveva con la formattazione predefinita di ostream, sei
    // cifre significative: ogni valore registrato differiva da quello misurato
    // senza che nulla lo dichiarasse.
    require(back.raw == 17.181411743164062,
            "the raw value must be recorded without losing a single digit");
    require(back.value == ias_sample.value,
            "the engineering value must be recorded without losing a single digit");

    // Un valore che la formattazione a sei cifre avrebbe certamente rovinato.
    efis::Sample<double> precise{};
    precise.value = 0.1234567890123456;
    precise.raw = 123456.789012345;
    precise.origin.signal = efis::SignalId::differential_pressure;
    precise.origin.unit = efis::Unit::hectopascal;
    precise.validity = efis::Validity::valid;
    std::ostringstream precise_out;
    efis::recording::FlightRecordWriter::write_header(precise_out);
    efis::recording::FlightRecordWriter::write_sample(precise_out, precise, epoch + 1s);
    std::istringstream precise_in{precise_out.str()};
    const auto precise_back = efis::recording::read_flight_record(precise_in);
    require(precise_back.samples.size() == 1, "the sample must be readable");
    require(precise_back.samples.front().sample.value == precise.value,
            "a value needing seventeen digits must come back exactly");
    require(precise_back.samples.front().sample.raw == precise.raw,
            "the raw value must come back exactly as well");

    // Registrazione interrotta a meta' riga: e' il caso della perdita di
    // alimentazione, e va contato, non nascosto.
    const std::string truncated = written.str().substr(0, written.str().size() - 12);
    std::istringstream truncated_in{truncated};
    const auto partial = efis::recording::read_flight_record(truncated_in);
    require(partial.malformed_rows >= 1,
            "an interrupted row must be counted as unreadable");
    require(!partial.samples.empty(),
            "what was written before the interruption must still be recovered");

    // Riga di un tipo sconosciuto: non e' un errore, e' una versione successiva.
    std::istringstream forward_in{
        std::string{"EFIS_RECORD_V2\nschema,2\nfuture_row,1,2,3\n"}};
    const auto forward = efis::recording::read_flight_record(forward_in);
    require(forward.unknown_rows == 1, "an unknown row type must be counted apart");
    require(forward.malformed_rows == 0, "an unknown row type is not a corrupt row");

    // Schema piu' recente di quello supportato: non si interpreta.
    std::istringstream newer_in{std::string{"EFIS_RECORD_V2\nschema,99\n"}};
    const auto newer = efis::recording::read_flight_record(newer_in);
    require(newer.schema_too_new,
            "a newer schema must be refused, not interpreted with today's meanings");
    require(newer.samples.empty(), "nothing must be read from a refused record");

    // Intestazione sbagliata: non e' un registro di volo.
    std::istringstream alien_in{std::string{"QUALCOS_ALTRO\n1,2,3\n"}};
    require(efis::recording::read_flight_record(alien_in).samples.empty(),
            "a file that is not a flight record must yield nothing");

    // --- Dal segmento su disco al replay -------------------------------------
    //
    // Le prove precedenti verificano il formato in memoria. Questa chiude il
    // cerchio richiesto dal paragrafo P1.5: il registratore a segmenti scrive un
    // file vero, e quel file si rilegge. Finche' il registratore usava il
    // formato V1 questo non era possibile, perche' un lettore non esisteva.
    const auto replay_directory = std::filesystem::temp_directory_path() /
        ("efis-replay-test-" + std::to_string(
            std::chrono::steady_clock::now().time_since_epoch().count()));
    {
        efis::recording::SegmentedRecorder segmented{
            replay_directory, {.records_per_segment = 4, .flush_every_records = 1}};
        efis::SimulationProvider replay_source{5};
        for (int tick = 1; tick <= 4; ++tick) {
            segmented.append(replay_source.sample(epoch + std::chrono::seconds{tick},
                                                  std::chrono::seconds{tick}));
        }
        segmented.close();
    }

    std::vector<std::filesystem::path> segments;
    for (const auto& entry : std::filesystem::directory_iterator{replay_directory}) {
        if (entry.path().extension() == ".csv") segments.push_back(entry.path());
    }
    require(segments.size() == 1, "the recorder must have closed one segment");

    std::ifstream segment_file{segments.front(), std::ios::binary};
    const auto from_disk = efis::recording::read_flight_record(segment_file);
    require(from_disk.schema == 2, "a segment on disk must declare its schema");
    require(from_disk.malformed_rows == 0,
            "a segment closed cleanly must contain no unreadable row");
    require(from_disk.samples.size() == 64,
            "four snapshots of sixteen signals must come back as sixty-four samples");

    const auto disk_airspeed = find_recorded(from_disk.samples,
                                             efis::SignalId::indicated_airspeed);
    require(disk_airspeed.present,
            "the airspeed must be identifiable by its signal after a disk round trip");
    require(disk_airspeed.sample.origin.unit == efis::Unit::knot,
            "the unit must survive the disk round trip");
    require(disk_airspeed.sample.is_simulated(),
            "a recording made from simulated data must still say so on replay");
    // Il flusso va chiuso prima di cancellare la cartella: su Windows un file
    // ancora aperto non e' cancellabile, e remove_all solleva un'eccezione. Su
    // Linux la cancellazione riesce comunque, ed e' il motivo per cui il difetto
    // si vedeva soltanto su una delle due piattaforme.
    segment_file.close();
    std::filesystem::remove_all(replay_directory);

    // --- Trasporto e replay, ADR-003 -----------------------------------------
    //
    // Il trasporto muove byte e non sa cosa trasportano; l'adapter interpreta
    // MAVLink e non sa da dove arrivino i byte. A unirli e' chi li usa. Questa
    // separazione e' la ragione per cui la stessa catena funzionera' su seriale
    // e su rete senza toccare ne' l'uno ne' l'altro.
    efis::io::RecordedByteSource replay_source{capture_path, 512};
    require(replay_source.size() == 68443, "the replay must load the whole replay_source");
    require(!replay_source.exhausted(), "a replay_source just opened is not exhausted");

    // La consegna e' frammentata di proposito: una seriale non allinea mai i
    // dati ai confini dei messaggi, e un replay che restituisse tutto in una
    // volta non eserciterebbe il caso normale.
    std::array<std::uint8_t, 4096> transfer{};
    require(replay_source.read(std::span<std::uint8_t>{transfer.data(), transfer.size()}) == 512,
            "the replay must honour its chunk size, not the caller buffer");
    replay_source.rewind();
    require(replay_source.position() == 0, "rewinding must return to the beginning");

    // Il replay guida l'adapter senza che nessuno dei due conosca l'altro.
    efis::MavlinkAdapter transport_adapter{{.stale_after = 1000ms, .lost_after = 3000ms}};
    const auto moved = efis::io::pump(replay_source, transport_adapter, arrival);
    require(moved == 68443, "the pump must move every byte of the replay_source");
    require(replay_source.exhausted(), "the replay_source must be exhausted once drained");

    // Stessi byte, stesso risultato: e' cio' che rende il replay un banco e non
    // un aneddoto. Il paragrafo 17.3 dell'handoff chiede esattamente questo.
    require(transport_adapter.parser_statistics().frames ==
                adapter.parser_statistics().frames,
            "replaying through the transport must decode the same frames");
    require(transport_adapter.statistics().frames_applied ==
                adapter.statistics().frames_applied,
            "replaying through the transport must apply the same messages");
    require(transport_adapter.snapshot().attitude.roll_deg.value ==
                adapter.snapshot().attitude.roll_deg.value,
            "the transport must not alter a single value");
    require(transport_adapter.snapshot().position.latitude_deg.validity ==
                efis::Validity::unavailable,
            "the validity rules must survive the change of transport");

    // Due riproduzioni della stessa registrazione devono coincidere fino
    // all'ultimo campione: senza determinismo un banco non dimostra nulla.
    replay_source.rewind();
    efis::MavlinkAdapter second_pass{{.stale_after = 1000ms, .lost_after = 3000ms}};
    efis::io::pump(replay_source, second_pass, arrival);
    require(second_pass.parser_statistics().frames == transport_adapter.parser_statistics().frames,
            "two replays of one replay_source must decode the same frame count");
    require(second_pass.snapshot().air_data.pressure_altitude_ft.value ==
                transport_adapter.snapshot().air_data.pressure_altitude_ft.value,
            "two replays of one replay_source must end on the same values");
    require(second_pass.statistics().sequence_wraps == transport_adapter.statistics().sequence_wraps,
            "even the sequence wrap count must be reproducible");

    // Dimensione del blocco diversa, stesso risultato: i confini di consegna non
    // devono influenzare cio' che si decodifica.
    efis::io::RecordedByteSource fragmented{capture_path, 7};
    efis::MavlinkAdapter piecemeal{{.stale_after = 1000ms, .lost_after = 3000ms}};
    efis::io::pump(fragmented, piecemeal, arrival, 64);
    require(piecemeal.parser_statistics().frames == transport_adapter.parser_statistics().frames,
            "fragmentation must not change how many frames are recovered");

    // Una sorgente vuota non e' un errore: non ha nulla da dare e lo dichiara.
    efis::io::RecordedByteSource empty_source{std::vector<std::uint8_t>{}};
    efis::MavlinkAdapter idle{};
    require(empty_source.exhausted(), "an empty source is exhausted from the start");
    require(efis::io::pump(empty_source, idle, arrival) == 0,
            "an empty source must move no bytes and must not hang");
    require(idle.parser_statistics().frames == 0,
            "no bytes can produce no frames");

    std::cout << "All EFIS core tests passed\n";
}
